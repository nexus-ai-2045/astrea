// フェーズ1の出迎え。ここだけはモデルを呼ばない。
//
// 理由は 2 つある。
//
// 1. コスト面の穴を塞ぐため。メッセージが無い初回リクエストでも CLI プロセスを
//    起動して日次予算を 1 消費していたので、新しい UUID を投げ続けるだけで
//    全体共有の予算を枯らせた (2026-08-07 セキュリティ監査)。出迎えは相談者の
//    入力に依存しない定型なので、生成する必要が無い。
// 2. 初回表示が即時になる。モデルの最初の文字は warm ターンでも 0.8〜1.5 秒
//    かかるので、開いた瞬間に無言の間が生まれていた。
//
// 文面は system prompt のフェーズ1 (温かく迎え、生年月日を聞き、軽い
// アイスブレイクを1つ添える) に沿わせること。ここを変えるときは
// system-prompt.ts のフェーズ1 も一緒に見る。

export const OPENING_GREETINGS: readonly string[] = [
  "よくいらっしゃいました。星々があなたの訪れを待っておりました。\n\nまずは、あなたが生まれた日を教えてくださいますか。それと、今日はどんな心持ちでここへ来られたのでしょう。",
  "ようこそ。ここは急ぐ場所ではありませんから、ゆっくりで構いません。\n\nはじめに、あなたの生まれた日を伺わせてください。あわせて、いま胸にあることを一言だけでも聞かせてもらえますか。",
  "お待ちしておりました。この時間に何かしら意味があるのだろうと思います。\n\nあなたが生まれた日を教えてください。それから、今日はどんな一日でしたか。",
  "いらっしゃいませ。星の巡りが、あなたをここへ運んできたようですね。\n\nまず、生まれた日を伺えますか。そして、いまいちばん心に引っかかっていることを聞かせてください。",
];

/**
 * 出迎えを 1 つ選ぶ。
 *
 * index を渡さなければランダム。テストから決定的に選べるように引数を残してある。
 * 範囲外の index でも必ず 1 つ返す (呼び出し側で握る条件を増やさないため)。
 */
export function pickOpeningGreeting(index?: number): string {
  const n = OPENING_GREETINGS.length;
  if (index === undefined || !Number.isFinite(index)) {
    return OPENING_GREETINGS[Math.floor(Math.random() * n)];
  }
  return OPENING_GREETINGS[((Math.trunc(index) % n) + n) % n];
}
